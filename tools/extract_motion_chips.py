#!/usr/bin/env python3
# extract_motion_chips.py — Tier B chip extraction (verbatim per-frame copy).
# Tier B 芯片提取（逐帧照搬）。
#
# Crops every frame's full 32x32 cell from the reference sheet into a chip, so
# playback is pixel-exact by construction (bob, two-tone leg swap, the side-view
# far-arm on f2/f3, the straight front/back legs — all baked into the pixels).
# Derives the reskin palette map by aligning the SAME palette ROLE across
# chibi_standard.json and chibi_alt.json (role alignment is authoritative; naive
# pixel matching confuses roles that share an RGB like hair_highlight/gold).
# 把参考图每帧的整 32×32 格裁成芯片 —— 回放天然逐像素精确（起伏、两棕换色、
# 侧视远臂 f2/f3、正背直腿……全烘在像素里）。换皮映射按【同一调色板 role】对齐
# chibi_standard.json 与 chibi_alt.json 生成（role 对齐权威；朴素像素匹配会把
# 同 RGB 的 role 如 hair_highlight/gold 搞混）。
#
# Usage:
#   python3 -I tools/extract_motion_chips.py \
#     --sheet assets/reference_sheet.png \
#     --standard assets/templates/chibi_standard.json \
#     --alt assets/templates/chibi_alt.json \
#     --out assets/templates/motion_chips

import argparse
import json
import os
import sys
from PIL import Image

CELL = 32

# The 6 flipbooks: (name, sheet row, frame count, fps). Idle rows hold 2 cells,
# walk rows hold 6. Row order in the sheet is front/side/back x idle/walk.
# 六本翻页书：(名, 表行, 帧数, fps)。待机行 2 格，行走行 6 格。
# 表中行序 = 正/侧/背 × 待机/行走。
FLIPBOOKS = [
    ("front_idle", 0, 2, 4),
    ("front_walk", 1, 6, 10),
    ("side_idle",  2, 2, 4),
    ("side_walk",  3, 6, 10),
    ("back_idle",  4, 2, 4),
    ("back_walk",  5, 6, 10),
]


def load_rgba(path):
    return Image.open(path).convert("RGBA")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", required=True)
    ap.add_argument("--standard", required=True)
    ap.add_argument("--alt", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    sheet = load_rgba(args.sheet)
    if sheet.size != (CELL * 6, CELL * 6):
        sys.exit(f"reference sheet must be {CELL*6}x{CELL*6}, got {sheet.size}")

    chips_dir = os.path.join(args.out, "chips")
    os.makedirs(chips_dir, exist_ok=True)

    # ---- crop chips / 裁芯片 ----
    index_lines = [
        "# motion chips manifest / generated by tools/extract_motion_chips.py",
        "# 逐帧芯片清单 / 由 tools/extract_motion_chips.py 生成。每帧 = 一整 32x32 格。",
        "# flipbook <name> <frames> <fps> <sheet_row>  ; chip file = chips/<name>_<i>.png",
        f"source {os.path.relpath(args.sheet)}",
        f"cell {CELL}",
    ]
    for name, row, frames, fps in FLIPBOOKS:
        index_lines.append(f"flipbook {name} {frames} {fps} {row}")
        for f in range(frames):
            cell = sheet.crop((f * CELL, row * CELL, (f + 1) * CELL, (row + 1) * CELL))
            chip_path = os.path.join(chips_dir, f"{name}_{f}.png")
            cell.save(chip_path)
            # Self-verify: written chip == source cell (identity crop). Compare raw
            # RGBA bytes (getdata() is deprecated in Pillow 14).
            # 自检：写出的芯片 == 源格（恒等裁剪）。比对原始 RGBA 字节
            # （getdata() 在 Pillow 14 弃用）。
            again = load_rgba(chip_path)
            if again.tobytes() != cell.tobytes():
                sys.exit(f"chip {chip_path} != source cell (write/read mismatch)")
    with open(os.path.join(args.out, "index.txt"), "w") as fh:
        fh.write("\n".join(index_lines) + "\n")

    # ---- palette map by ROLE alignment / 按 role 对齐生成换皮映射 ----
    std = json.load(open(args.standard))
    alt = json.load(open(args.alt))
    std_pal, alt_pal = std["palette"], alt["palette"]
    missing = [r for r in std_pal if r not in alt_pal]
    if missing:
        sys.exit(f"alt palette missing roles: {missing}")

    # Write as BGRA to match cv::Vec4b. One pair per line: "sB,sG,sR,sA dB,dG,dR,dA".
    # 按 BGRA 写出以匹配 cv::Vec4b。每行一对。
    pal_path = os.path.join(args.out, "palette_map.txt")
    with open(pal_path, "w") as fh:
        fh.write("# reskin palette map (BGRA): original -> alt, aligned by palette role\n")
        fh.write("# 换皮调色板映射（BGRA）：原版 -> 换皮，按调色板 role 对齐。\n")
        fh.write("# <sB,sG,sR,sA> <dB,dG,dR,dA> per line / 每行一对。\n")
        for role in sorted(std_pal):
            s = std_pal[role]
            a = alt_pal[role]
            # RGB -> BGRA, alpha 255
            fh.write(f"{s[2]},{s[1]},{s[0]},255 {a[2]},{a[1]},{a[0]},255\n")

    # ---- coverage check / 覆盖检查 ----
    # Every non-transparent chip colour must be a key in the map (else reskin
    # leaves it untouched — a silent bug). Report any stragglers.
    # 芯片里每个非透明色都必须是映射的键（否则换皮漏掉它 —— 隐性 bug）。报告遗漏。
    mapped = {f"{s[2]},{s[1]},{s[0]},255" for s in (std_pal[r] for r in std_pal)}
    unmapped = set()
    total_frames = 0
    for name, row, frames, fps in FLIPBOOKS:
        for f in range(frames):
            total_frames += 1
            chip = load_rgba(os.path.join(chips_dir, f"{name}_{f}.png"))
            raw = chip.tobytes()  # RGBA RGBA ... / 原始 RGBA 字节
            for i in range(0, len(raw), 4):
                r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
                if a == 0:
                    continue
                if f"{b},{g},{r},{a}" not in mapped:
                    unmapped.add((b, g, r, a))

    print(f"wrote {len(FLIPBOOKS)} flipbooks / {total_frames} chips -> {args.out}")
    print(f"palette map: {len(std_pal)} roles -> {pal_path}")
    if unmapped:
        print(f"WARNING unmapped non-transparent colours (BGRA): {sorted(unmapped)}")
    else:
        print("coverage OK: every non-transparent chip colour is in the map")


if __name__ == "__main__":
    main()
